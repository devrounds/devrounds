package portmap

import (
	"fmt"
	"io"
	"strings"
)

// redactHome swaps the user's home folder for ~ so a report can be shared.
func redactHome(s, home string) string {
	if home == "" {
		return s
	}
	for _, sep := range []string{`\`, "/"} {
		s = strings.ReplaceAll(s, home+sep, "~"+sep)
	}
	if strings.HasSuffix(s, home) {
		s = strings.TrimSuffix(s, home) + "~"
	}
	return s
}

func mdCell(s, home string) string {
	s = redactHome(s, home)
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", " ")
	if s == "" {
		return "-"
	}
	return s
}

// PrintMarkdown writes the report as a Markdown document that is safe to share:
// the home folder is shown as ~ and no environment values are included.
func PrintMarkdown(w io.Writer, r Report, home string) {
	fmt.Fprintln(w, "# Port map")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "_Generated by devrounds. Your home folder is shown as ~. No environment values are included._")
	fmt.Fprintln(w)

	fmt.Fprintln(w, "## Listening ports")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Port | Process | PID | Folder | Container |")
	fmt.Fprintln(w, "|---|---|---|---|---|")
	for _, p := range r.Ports {
		fmt.Fprintf(w, "| %d | %s | %d | %s | %s |\n", p.Port, mdCell(p.Process, home), p.PID, mdCell(p.Folder, home), mdCell(p.Container, home))
	}

	if len(r.Containers) > 0 {
		fmt.Fprintln(w)
		fmt.Fprintln(w, "## Containers")
		fmt.Fprintln(w)
		fmt.Fprintln(w, "| Container | Image | Compose | Ports | Status |")
		fmt.Fprintln(w, "|---|---|---|---|---|")
		for _, c := range r.Containers {
			compose := ""
			if c.Project != "" {
				compose = c.Project + "/" + c.Service
			}
			fmt.Fprintf(w, "| %s | %s | %s | %s | %s |\n", mdCell(c.Name, home), mdCell(c.Image, home), mdCell(compose, home), mdCell(c.Ports, home), mdCell(c.Status, home))
		}
	}

	if p := r.Project; p != nil {
		fmt.Fprintln(w)
		fmt.Fprintf(w, "## Project: %s\n\n", p.Name)
		switch {
		case p.Expected == 0:
			fmt.Fprintln(w, "- No specific ports named (looked in Compose files and .env.example).")
		case len(p.Conflicts) == 0:
			fmt.Fprintf(w, "- No port conflicts (%d expected ports checked).\n", p.Expected)
		default:
			for _, c := range p.Conflicts {
				fmt.Fprintf(w, "- **Port %d** (%s) is held by %s\n", c.Port, c.Source, redactHome(c.Holder, home))
			}
		}
	}

	if len(r.Health) > 0 {
		fmt.Fprintln(w)
		fmt.Fprintln(w, "## Health checks")
		fmt.Fprintln(w)
		fmt.Fprintln(w, "| URL | Result |")
		fmt.Fprintln(w, "|---|---|")
		for _, h := range r.Health {
			res := h.Verdict
			if h.Status > 0 {
				res = fmt.Sprintf("%s (%d, %d ms)", h.Verdict, h.Status, h.Millis)
			}
			fmt.Fprintf(w, "| %s | %s |\n", h.URL, res)
		}
	}

	if !r.Docker {
		fmt.Fprintln(w)
		fmt.Fprintln(w, "> Docker was not found or is not running, so containers are not listed.")
	}
}
